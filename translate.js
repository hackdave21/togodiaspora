// Initialisation du sélecteur de langues
document.addEventListener('DOMContentLoaded', function() {
	const languageToggle = document.getElementById('languageToggle');
	const languageDropdown = document.getElementById('languageDropdown');
	const languageOptions = document.querySelectorAll('.language-option');

	// Basculer le menu déroulant
	if (languageToggle) {
		languageToggle.addEventListener('click', function(e) {
			e.stopPropagation();
			languageDropdown.classList.toggle('show');
		});
	}

	// Fermer le menu en cliquant ailleurs
	document.addEventListener('click', function() {
		if (languageDropdown) {
			languageDropdown.classList.remove('show');
		}
	});

	// Sélection de langue
	languageOptions.forEach(option => {
		option.addEventListener('click', function() {
			const selectedLang = this.getAttribute('data-lang');
			changeLanguage(selectedLang);
			languageDropdown.classList.remove('show');
		});
	});

	// Charger la langue sauvegardée
	const savedLanguage = localStorage.getItem('selectedLanguage') || 'fr';
	if (savedLanguage !== 'fr') {
		changeLanguage(savedLanguage);
	}
});

// Fonction de changement de langue
function changeLanguage(lang) {
	if (!translations[lang]) return;

	currentLanguage = lang;
	
	// Mettre à jour tous les éléments traduisibles
	document.querySelectorAll('[data-translate]').forEach(element => {
		const key = element.getAttribute('data-translate');
		if (translations[lang][key]) {
			element.textContent = translations[lang][key];
		}
	});

	// Mettre à jour le drapeau et le nom de la langue actuelle
	const currentFlag = document.getElementById('currentFlag');
	const currentLanguageSpan = document.querySelector('[data-translate="current_language"]');
	
	if (currentFlag) {
		currentFlag.src = languageFlags[lang];
	}
	
	if (currentLanguageSpan) {
		currentLanguageSpan.textContent = translations[lang].current_language;
	}

	// Mettre à jour l'option de langue active
	document.querySelectorAll('.language-option').forEach(option => {
		option.classList.remove('active');
		if (option.getAttribute('data-lang') === lang) {
			option.classList.add('active');
		}
	});

	// Mettre à jour l'attribut lang du HTML
	document.documentElement.lang = lang;

	// Sauvegarder la préférence de langue
	localStorage.setItem('selectedLanguage', lang);

	// Mettre à jour le titre de la page selon la langue
	const titles = {
		fr: "Togo Diaspora - Accueil",
		en: "Togo Diaspora - Home", 
		de: "Togo Diaspora - Startseite"
	};
	document.title = titles[lang];
}

// Fonction utilitaire pour ajouter de nouvelles traductions dynamiquement
function addTranslations(newTranslations) {
	Object.keys(newTranslations).forEach(lang => {
		if (translations[lang]) {
			Object.assign(translations[lang], newTranslations[lang]);
		}
	});
}